def finalize_with(reflector: Any, directory: Any = BASE) -> FinalizedExperience:
    case = read_json(directory / "input.json")
    captured, _ = capture_finalize_case(case)
    return run(finalize_async(captured, **finalize_arguments(case), reflector=reflector))



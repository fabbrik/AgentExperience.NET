class ReplyClient(BaseChatClient[Any]):
    """A chat client that records the one call it is sent and answers it as ``reply.json`` says."""

    def __init__(self, reply: dict[str, Any], *, ignore_cancellation: bool = False) -> None:
        super().__init__()
        self.reply = reply
        self.ignore_cancellation = ignore_cancellation
        self.messages: list[Message] | None = None
        self.options: dict[str, Any] | None = None
        self.calls = 0

    def _inner_get_response(self, *, messages: Sequence[Message], stream: bool, options: Any, **_: Any) -> Any:
        self.calls += 1
        self.messages = list(messages)
        self.options = dict(options)
        reply = self.reply

        async def respond() -> ChatResponse:
            delay = reply.get("delayMilliseconds", 0)
            if delay:
                if self.ignore_cancellation:
                    try:
                        await asyncio.sleep(delay / 1000)
                    except asyncio.CancelledError:
                        await asyncio.sleep(delay / 1000)
                else:
                    await asyncio.sleep(delay / 1000)
            if reply.get("throws"):
                raise RuntimeError("The provider answered 500 with a body quoting the prompt.")
            return ChatResponse(
                messages=[
                    Message(role=message["role"], contents=[content_of(item) for item in message["contents"]])
                    for message in reply["messages"]
                ],
                model=reply.get("modelId"),
            )

        return respond()


def content_of(item: dict[str, Any]) -> Content:
    kind = item["type"]
    if kind == "text":
        return Content.from_text(item["text"])
    if kind == "reasoning":
        return Content.from_text_reasoning(text=item["text"])
    if kind == "functionCall":
        return Content.from_function_call(item["callId"], item["name"])
    if kind == "functionResult":
        return Content.from_function_result(item["callId"], result=item.get("text"))
    raise AssertionError(f"Unknown content type {kind}")


def options_of(value: dict[str, Any]) -> ChatReflectorOptions:
    return ChatReflectorOptions(
        model_name=value["modelName"],
        timeout=value["timeoutSeconds"],
        max_quoted_length=value["maxQuotedLength"],
        max_prompt_length=value["maxPromptLength"],
        temperature=value["temperature"],
        max_output_tokens=value["maxOutputTokens"],
    )


class Capturing:
    """The reflector, recording the request it was asked about; it declares the same run content."""

    def __init__(self, inner: ChatClientExperienceReflector) -> None:
        self.inner = inner
        self.request: ReflectionRequest | None = None

    async def reflect(self, request: ReflectionRequest) -> Reflection:
        self.request = request
        return await self.inner.reflect(request)

    def reflected_run_content(self, request: ReflectionRequest) -> list[str]:
        return self.inner.reflected_run_content(request)


def run_case(directory: Any, capturing: bool = False) -> tuple[FinalizedExperience, ReplyClient, Capturing | None]:
    case = read_json(directory / "input.json")
    client = ReplyClient(read_json(directory / "reply.json"))
    reflector = ChatClientExperienceReflector(client, options_of(read_json(directory / "reflector.json")))
    wrapper = Capturing(reflector) if capturing else None
    captured, _ = capture_finalize_case(case)
    finalized = run(finalize_async(captured, **finalize_arguments(case), reflector=wrapper or reflector))
    return finalized, client, wrapper


def assert_json(expected: Any, actual: Any, what: str) -> None:
    difference = json_difference(expected, json.loads(json.dumps(actual)))
    assert difference is None, f"{what}: {difference}"


@pytest.mark.parametrize("name", cases("reflection-prompt"))
def test_reflection_prompt(name: str) -> None:
    directory = PROMPT / name
    _, client, wrapper = run_case(directory, capturing=True)
    assert client.messages is not None and client.options is not None and wrapper is not None
    assert [{"role": message.role, "text": message.text} for message in client.messages] == read_json(
        directory / "expected-messages.json"
    )
    options = client.options
    expected = read_json(directory / "expected-options.json")
    response_format = options["response_format"]
    assert response_format["type"] == "json_schema"
    actual = {
        "modelId": options.get("model"),
        "temperature": options.get("temperature"),
        "maxOutputTokens": options["max_tokens"],
        "toolMode": {"none": "None"}[options["tool_choice"]],
        "tools": options.get("tools"),
        "responseFormat": {
            "schemaName": response_format["json_schema"]["name"],
            "schemaDescription": response_format["json_schema"]["description"],
            "schema": response_format["json_schema"]["schema"],
        },
    }
    assert_json(expected, actual, "expected-options.json")
    assert wrapper.request is not None
    assert wrapper.inner.reflected_run_content(wrapper.request) == read_json(directory / "expected-shown.json")


def output_json(finalized: FinalizedExperience) -> dict[str, Any]:
    failure = finalized.reflection_failure
    return {
        "outcome": finalized.record.status,
        "reflectionFailure": None
        if not isinstance(failure, ReflectionFailed)
        else {"kind": failure.kind, "causeType": failure.cause_type, "message": str(failure)},
        "screening": None
        if finalized.screening_refusal_code is None
        else {"refusal": finalized.screening_refusal_code, "reason": finalized.screening_refusal},
    }


@pytest.mark.parametrize("name", cases("reflection-output"))
def test_reflection_output(name: str) -> None:
    directory = OUTPUT / name
    finalized, _, _ = run_case(directory)
    expected = read_json(directory / "expected.json")
    actual = output_json(finalized)
    # The cause's type is the port's own: compare that there is one, and the message with it in.
    expected_failure, actual_failure = expected["reflectionFailure"], actual["reflectionFailure"]
    if expected_failure is not None and expected_failure["causeType"] is not None:
        assert actual_failure is not None and actual_failure["causeType"] is not None
        expected_failure["message"] = expected_failure["message"].replace(
            expected_failure["causeType"], actual_failure["causeType"]
        )
        expected_failure["causeType"] = actual_failure["causeType"]
    assert_json(expected, actual, "expected.json")
    assert_json(read_json(directory / "expected-record.json"), to_stored(finalized.record), "expected-record.json")
    assert_json(read_json(directory / "expected-event.json"), finalized.event.to_json(), "expected-event.json")



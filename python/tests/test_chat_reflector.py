def test_the_callback_cannot_offer_tools_or_raise_the_cap() -> None:
    def configure(options: dict[str, Any]) -> None:
        options["tools"] = ["a tool"]
        options["tool_choice"] = "auto"
        options["max_tokens"] = 100_000
        options["seed"] = 7

    client = ReplyClient(VALID)
    finalized = finalize_with(
        ChatClientExperienceReflector(client, ChatReflectorOptions(configure_chat_options=configure))
    )
    assert finalized.record.status == "Validated"
    assert client.options is not None
    assert "tools" not in client.options
    assert client.options["tool_choice"] == "none"

def test_a_host_reflector_that_raises_or_returns_a_mismatched_reflection_quarantines() -> None:
    class Raises:
        def reflect(self, request: ReflectionRequest) -> Reflection:
            raise LookupError("no")

    class Mismatched:
        def reflect(self, request: ReflectionRequest) -> Reflection:
            from agentexperience.reflector import DeterministicReflector

            reflection = DeterministicReflector().reflect(request)
            from dataclasses import replace

            return replace(reflection, reflection_id=uuid.uuid4())

    case = read_json(BASE / "input.json")
    for reflector, error in ((Raises(), LookupError), (Mismatched(), ValueError)):
        captured, _ = capture_finalize_case(case)
        finalized = finalize(captured, **finalize_arguments(case), reflector=reflector)
        assert finalized.record.status == "Quarantined"
        assert isinstance(finalized.reflection_failure, error)
    mismatch = finalize(capture_finalize_case(case)[0], **finalize_arguments(case), reflector=Mismatched())
    assert getattr(mismatch.reflection_failure, "field", None) == "ReflectionId"

def test_a_sink_returning_none_is_an_error() -> None:
    case = FAMILY / "measured-helps-only"
    options = read_json(case / "options.json")
    now = Instant.parse(options["now"])

    class Nothing:
        def sync(self, scope: Scope, current: Any) -> Any:
            return None

    view = ExperienceLessons(memory_store(read_json(case / "seed.json")), clock=lambda: now)
    with pytest.raises(RuntimeError):
        view.export_measured(Nothing(), ExperienceIdentity("p", scope_of(options["scope"])), BenefitOptions(3))
    with pytest.raises(ValueError):
        BenefitOptions(0)

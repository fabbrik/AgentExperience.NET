FAMILY = FIXTURES / "lesson-export"


def result_json(result: LessonExportResult) -> dict[str, Any]:
    return {
        "outcome": result.outcome,
        "holdoutTracked": result.holdout_tracked,
        "exportedAt": result.exported_at.format(),
        "lessons": [
            {
                "experienceId": str(lesson.experience_id),
                "revision": lesson.revision,
                "taskId": lesson.task_id,
                "lessonText": lesson.lesson_text,
                "measuredBenefit": comparison_to_json(lesson.measured_benefit),
                "exportedAt": lesson.exported_at.format(),
            }
            for lesson in result.lessons
        ],
        "sync": None
        if result.sync is None
        else {"added": result.sync.added, "updated": result.sync.updated, "removed": result.sync.removed},
    }


def export_case(
    name: str, directory: Path, via: Any = None, make_store: Any = memory_store
) -> tuple[LessonExportResult, bytes | None]:
    """Runs a case: the seed in an in-memory store, exported at the case's clock to a Markdown sink writing in
    ``directory``, which first holds ``previous.md`` when the case has one."""
    case = FAMILY / name
    options = read_json(case / "options.json")
    now = Instant.parse(options["now"])
    store = make_store(read_json(case / "seed.json"))
    path = directory / "lessons.md"
    if options["hasPreviousFile"]:
        path.write_bytes((case / "previous.md").read_bytes())
    identity = ExperienceIdentity(
        "contract-principal", scope_of(options["scope"]), AuthorizationBounds.of(scope_of(options["authorizedScope"]))
    )
    minimum = options["minimumRunsPerArm"]
    lessons = via(store, now) if via is not None else ExperienceLessons(store, clock=lambda: now)
    result = lessons.export_measured(
        MarkdownLessonFileSink(path, clock=lambda: now),
        identity,
        None if minimum is None else BenefitOptions(minimum),
    )
    return result, path.read_bytes() if path.exists() and result.sync is not None else None


@pytest.mark.parametrize("name", cases("lesson-export"))
def test_lesson_export(name: str, tmp_path: Path) -> None:
    result, written = export_case(name, tmp_path)
    difference = json_difference(read_json(FAMILY / name / "expected.json"), result_json(result))
    assert difference is None, difference
    assert (written or b"") == (FAMILY / name / "expected.md").read_bytes()



# ---- The sink ----------------------------------------------------------------------------------------------------

SCOPE = Scope("tenant", "app", "project", agent_id="agent")
NOW = Instant.parse("2026-03-03T09:00:00.1234567+00:00")


def comparison(difference: float | None = 1.0, lower: float | None = 0.25, upper: float | None = 1.0) -> Any:
    return BenefitComparison(BenefitArm(3, 3), BenefitArm(3, 0), difference, lower, upper, "Helps", 0, 0, 0)


def lesson(n: int, text: str = "Lesson: Wait.\n", revision: int = 1) -> ExportedLesson:
    return ExportedLesson(uuid.UUID(int=n), revision, "task", text, comparison(), NOW)


def test_a_blank_path_is_refused_and_a_path_is_made_absolute(tmp_path: Path) -> None:
    for blank in ("", "  \t"):
        with pytest.raises(ValueError):
            MarkdownLessonFileSink(blank)
    with pytest.raises(TypeError):
        MarkdownLessonFileSink(None)  # type: ignore[arg-type]
    relative = MarkdownLessonFileSink(os.path.join("..", "x.md"))
    assert os.path.isabs(relative.path) and ".." not in relative.path.split(os.sep)


def test_a_crlf_file_counts_its_sections(tmp_path: Path) -> None:
    path = tmp_path / "lessons.md"
    sink = MarkdownLessonFileSink(path, clock=lambda: NOW)
    sink.sync(SCOPE, [lesson(1), lesson(2)])
    path.write_bytes(path.read_bytes().replace(b"\n", b"\r\n"))
    assert sink.sync(SCOPE, [lesson(1), lesson(3)]) == LessonSyncResult(1, 0, 1)
    assert b"\r" not in path.read_bytes()


def test_the_file_is_rewritten_whole_sorted_and_deduplicated(tmp_path: Path) -> None:
    path = tmp_path / "lessons.md"
    sink = MarkdownLessonFileSink(path, clock=lambda: NOW)
    assert sink.sync(SCOPE, [lesson(2), lesson(1), lesson(1, "Lesson: second copy.\n")]) == LessonSyncResult(2, 0, 0)
    text = path.read_text(encoding="utf-8")
    assert text.index(str(uuid.UUID(int=1))) < text.index(str(uuid.UUID(int=2)))
    assert "second copy" not in text
    assert sink.sync(SCOPE, [lesson(1, revision=2)]) == LessonSyncResult(0, 1, 1)
    assert sink.sync(SCOPE, []) == LessonSyncResult(0, 0, 1)
    assert "Lessons: 0\n" in path.read_text(encoding="utf-8")


def test_a_failed_write_leaves_the_file_and_no_temporary(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    path = tmp_path / "lessons.md"
    path.write_text("before", encoding="utf-8")

    def fail(source: str, target: str) -> None:
        raise OSError("disk full")

    monkeypatch.setattr(os, "replace", fail)
    with pytest.raises(OSError, match="disk full"):
        MarkdownLessonFileSink(path, clock=lambda: NOW).sync(SCOPE, [lesson(1)])
    assert path.read_text(encoding="utf-8") == "before"
    assert sorted(entry.name for entry in tmp_path.iterdir()) == ["lessons.md"]


def test_a_missing_directory_raises(tmp_path: Path) -> None:
    with pytest.raises(OSError):
        MarkdownLessonFileSink(tmp_path / "missing" / "lessons.md", clock=lambda: NOW).sync(SCOPE, [lesson(1)])


def test_code_blocks_keep_every_line_inside(tmp_path: Path) -> None:
    path = tmp_path / "lessons.md"
    MarkdownLessonFileSink(path, clock=lambda: NOW).sync(
        SCOPE, [lesson(1, "Lesson: one\r\n## Lesson injected\rthree\n\n\n")]
    )
    text = path.read_text(encoding="utf-8")
    assert "    ## Lesson injected\n    three\n" in text
    assert "\n## Lesson injected" not in text


